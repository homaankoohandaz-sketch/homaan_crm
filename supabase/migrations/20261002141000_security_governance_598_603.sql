create table if not exists public.production_action_approvals (
  id bigint generated by default as identity primary key,
  agent_key text not null,
  action_type text not null,
  target_type text,
  target_id text,
  requested_by uuid not null default auth.uid() references auth.users(id),
  approved_by uuid references auth.users(id),
  status text not null default 'pending' check (status in ('pending','approved','rejected','executed','expired')),
  payload jsonb not null default '{}'::jsonb,
  reason text,
  created_at timestamptz not null default now(),
  approved_at timestamptz,
  executed_at timestamptz
);
alter table public.production_action_approvals enable row level security;
drop policy if exists production_action_approvals_insert on public.production_action_approvals;
create policy production_action_approvals_insert on public.production_action_approvals
for insert to authenticated
with check (requested_by = auth.uid() and status='pending');
drop policy if exists production_action_approvals_select on public.production_action_approvals;
create policy production_action_approvals_select on public.production_action_approvals
for select to authenticated
using (public.is_manager_user() or requested_by=auth.uid());
drop policy if exists production_action_approvals_update_manager on public.production_action_approvals;
create policy production_action_approvals_update_manager on public.production_action_approvals
for update to authenticated
using (public.is_manager_user()) with check (public.is_manager_user());
revoke all on public.production_action_approvals from anon, authenticated;
grant select,insert,update on public.production_action_approvals to authenticated;

