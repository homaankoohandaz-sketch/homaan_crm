create table if not exists public.security_field_policies (
  id bigint generated by default as identity primary key,
  entity_type text not null,
  field_name text not null,
  visibility text not null default 'manager_only',
  roles text[] not null default array['owner','admin','manager'],
  mask_strategy text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(entity_type,field_name)
);
alter table public.security_field_policies enable row level security;
drop policy if exists security_field_policies_manager on public.security_field_policies;
create policy security_field_policies_manager on public.security_field_policies
for all to authenticated using (public.is_manager_user()) with check (public.is_manager_user());
revoke all on public.security_field_policies from anon, authenticated;
grant select,insert,update,delete on public.security_field_policies to authenticated;

insert into public.security_field_policies(entity_type,field_name,visibility,roles,mask_strategy)
values
 ('person','phone','manager_only',array['owner','admin','manager'],'none'),
 ('person','emergency_phone','manager_only',array['owner','admin','manager'],'none'),
 ('property','mobile','manager_only',array['owner','admin','manager'],'none'),
 ('property','emergency_phone','manager_only',array['owner','admin','manager'],'none')
on conflict(entity_type,field_name) do update
set visibility=excluded.visibility,roles=excluded.roles,mask_strategy=excluded.mask_strategy,updated_at=now();

