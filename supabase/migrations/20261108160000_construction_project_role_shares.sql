-- Construction M6 project visibility: managers see all, advisors see owned/shared,
-- and customers see only explicitly shared projects.
create table if not exists public.construction_project_access (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.construction_projects(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  granted_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  revoked_at timestamptz,
  constraint construction_project_access_project_user_key unique (project_id, user_id)
);

create index if not exists construction_project_access_user_active_idx
  on public.construction_project_access(user_id, project_id)
  where revoked_at is null;

alter table public.construction_project_access enable row level security;
grant select, insert, update, delete on public.construction_project_access to authenticated;
grant usage, select on sequence public.construction_project_access_id_seq to authenticated;

drop policy if exists construction_project_access_select on public.construction_project_access;
create policy construction_project_access_select
  on public.construction_project_access for select to authenticated
  using (
    user_id = (select auth.uid())
    or exists (
      select 1 from public.app_roles r
      where r.user_id = (select auth.uid())
        and r.active = true
        and r.role in ('owner','admin','manager')
    )
  );

drop policy if exists construction_project_access_insert on public.construction_project_access;
create policy construction_project_access_insert
  on public.construction_project_access for insert to authenticated
  with check (
    granted_by = (select auth.uid())
    and exists (
      select 1 from public.app_roles r
      where r.user_id = (select auth.uid())
        and r.active = true
        and r.role in ('owner','admin','manager')
    )
  );

drop policy if exists construction_project_access_update on public.construction_project_access;
create policy construction_project_access_update
  on public.construction_project_access for update to authenticated
  using (
    exists (
      select 1 from public.app_roles r
      where r.user_id = (select auth.uid())
        and r.active = true
        and r.role in ('owner','admin','manager')
    )
  )
  with check (
    exists (
      select 1 from public.app_roles r
      where r.user_id = (select auth.uid())
        and r.active = true
        and r.role in ('owner','admin','manager')
    )
  );

drop policy if exists construction_project_access_delete on public.construction_project_access;
create policy construction_project_access_delete
  on public.construction_project_access for delete to authenticated
  using (
    exists (
      select 1 from public.app_roles r
      where r.user_id = (select auth.uid())
        and r.active = true
        and r.role in ('owner','admin','manager')
    )
  );

drop policy if exists phase_read_projects on public.construction_projects;
create policy phase_read_projects
  on public.construction_projects for select to authenticated
  using (
    exists (
      select 1 from public.app_roles r
      where r.user_id = (select auth.uid())
        and r.active = true
        and r.role in ('owner','admin','manager','staff','builder')
    )
    or (
      created_by = (select auth.uid())
      and exists (
        select 1 from public.app_roles r
        where r.user_id = (select auth.uid())
          and r.active = true
          and r.role in ('advisor','agent')
      )
    )
    or exists (
      select 1 from public.construction_project_access a
      where a.project_id = construction_projects.id
        and a.user_id = (select auth.uid())
        and a.revoked_at is null
    )
  );
