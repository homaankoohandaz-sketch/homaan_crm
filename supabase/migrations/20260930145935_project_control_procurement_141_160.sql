create table if not exists public.project_purchase_approvals (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.construction_projects(id) on delete cascade,
  procurement_id bigint not null references public.project_procurement(id) on delete cascade,
  requested_by uuid references auth.users(id),
  decided_by uuid references auth.users(id),
  status text not null default 'pending' check (status in ('pending','approved','rejected','cancelled')),
  requested_at timestamptz not null default now(),
  decided_at timestamptz,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.project_purchase_orders (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.construction_projects(id) on delete cascade,
  procurement_id bigint references public.project_procurement(id) on delete set null,
  po_number text not null,
  supplier_name text,
  ordered_at date,
  expected_delivery_at date,
  status text not null default 'draft' check (status in ('draft','submitted','confirmed','partially_received','received','cancelled')),
  quantity numeric not null default 0,
  unit text,
  unit_price_toman numeric not null default 0,
  total_price_toman numeric generated always as (quantity * unit_price_toman) stored,
  currency text not null default 'IRR',
  notes text,
  created_at timestamptz not null default now(),
  unique(project_id, po_number)
);

create table if not exists public.project_procurement_deliveries (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.construction_projects(id) on delete cascade,
  procurement_id bigint not null references public.project_procurement(id) on delete cascade,
  purchase_order_id bigint references public.project_purchase_orders(id) on delete set null,
  delivered_at date not null default current_date,
  quantity numeric not null default 0,
  accepted_quantity numeric not null default 0,
  rejected_quantity numeric not null default 0,
  notes text,
  created_at timestamptz not null default now(),
  check (quantity >= 0 and accepted_quantity >= 0 and rejected_quantity >= 0),
  check (accepted_quantity + rejected_quantity <= quantity)
);

create table if not exists public.project_material_inventory (
