create or replace view public.project_procurement_control
with (security_invoker=true) as
select p.*,
coalesce(p.quantity,0)-coalesce(p.received_quantity,0)-coalesce(p.rejected_quantity,0) outstanding_quantity,
case when coalesce(p.quantity,0)>0 then round((coalesce(p.received_quantity,0)/p.quantity)*100,2) else 0 end delivery_percent,
case when coalesce(p.purchase_price_toman,0)>0 then round(((coalesce(p.current_price_toman,0)-p.purchase_price_toman)/p.purchase_price_toman)*100,2) else 0 end live_price_variance_percent,
case when coalesce(p.procurement_risk_score,0)>=75 then 'critical'
when coalesce(p.procurement_risk_score,0)>=50 then 'high'
when coalesce(p.procurement_risk_score,0)>=25 then 'medium' else 'low' end calculated_risk_level
from public.project_procurement p;