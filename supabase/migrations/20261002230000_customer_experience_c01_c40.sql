-- BuildWise AI — Customer Experience C01-C40 persistence
-- Extends canonical customer/portal/security domains; no parallel customer engine.

create table if not exists public.customer_profiles (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  crm_person_id bigint references public.crm_people(id) on delete set null,
  profile jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customer_requirements (
  id bigint generated by default as identity primary key,
  customer_id bigint references public.crm_people(id) on delete cascade,
  intent text not null default 'general',
  requirements jsonb not null default '{}'::jsonb,
  missing_fields jsonb not null default '[]'::jsonb,
  status text not null default 'collecting' check (status in ('collecting','ready','matched','closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customer_location_recommendations (
  id bigint generated by default as identity primary key,
  customer_id bigint references public.crm_people(id) on delete cascade,
  location_name text not null,
  rank smallint not null check (rank between 1 and 4),
  score numeric not null default 0,
  price_tier text,
  evidence jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.customer_interactions (
  id bigint generated by default as identity primary key,
  customer_id bigint references public.crm_people(id) on delete cascade,
  entity_type text not null,
  entity_id bigint not null,
  interaction_type text not null,
  verified boolean not null default false,
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create table if not exists public.customer_ratings (
  id bigint generated by default as identity primary key,
  interaction_id bigint not null references public.customer_interactions(id) on delete cascade,
  customer_id bigint references public.crm_people(id) on delete cascade,
  entity_type text not null,
  entity_id bigint not null,
  rating_kind text not null default 'overall',
  score smallint not null check (score between 1 and 5),
  comment text not null default '',
  created_at timestamptz not null default now(),
  unique (interaction_id, rating_kind)
);

create table if not exists public.customer_experience_proposals (
  id bigint generated by default as identity primary key,
  customer_id bigint references public.crm_people(id) on delete cascade,
  entity_type text not null,
  entity_id bigint not null,
  customer_estimate numeric,
  price_min numeric,
  price_max numeric,
  evidence jsonb not null default '[]'::jsonb,
  roi jsonb not null default '{}'::jsonb,
  scenario jsonb not null default '{}'::jsonb,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists customer_requirements_customer_idx on public.customer_requirements(customer_id,created_at desc);
create index if not exists customer_location_recommendations_customer_idx on public.customer_location_recommendations(customer_id,rank);
create index if not exists customer_interactions_entity_idx on public.customer_interactions(entity_type,entity_id,occurred_at desc);
create index if not exists customer_ratings_entity_idx on public.customer_ratings(entity_type,entity_id,created_at desc);
create index if not exists customer_proposals_customer_idx on public.customer_experience_proposals(customer_id,created_at desc);

