-- Only verified interactions may produce public ratings.
create or replace function public.customer_rating_is_verified()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $function$
begin
  if not exists (
    select 1 from public.customer_interactions i
    where i.id=new.interaction_id and i.verified=true
      and i.customer_id=new.customer_id
      and i.entity_type=new.entity_type
      and i.entity_id=new.entity_id
  ) then
    raise exception 'verified_interaction_required';
  end if;
  return new;
end;
$function$;

drop trigger if exists customer_rating_verified_guard on public.customer_ratings;
create trigger customer_rating_verified_guard
before insert or update on public.customer_ratings
for each row execute function public.customer_rating_is_verified();

create or replace function public.customer_price_range(p_estimate numeric, p_tolerance numeric default 0.05)
returns jsonb
language sql
immutable
security invoker
as $function$
  select jsonb_build_object(
    'estimate',p_estimate,
    'min',p_estimate*(1-least(greatest(coalesce(p_tolerance,0.05),0),0.05)),
    'max',p_estimate*(1+least(greatest(coalesce(p_tolerance,0.05),0),0.05)),
    'tolerance_pct',least(greatest(coalesce(p_tolerance,0.05),0),0.05)*100
  )
$function$;

create or replace view public.customer_rating_aggregation
with (security_invoker=true)
as
select
  entity_type,
  entity_id,
  count(*) filter (where i.verified) as verified_count,
  round(avg(r.score) filter (where i.verified),2) as average_score,
  round((avg(r.score) filter (where i.verified))*20,2) as market_score
from public.customer_ratings r
join public.customer_interactions i on i.id=r.interaction_id
group by entity_type,entity_id;

create or replace view public.customer_verified_reviews
with (security_invoker=true)
as
select r.id,r.entity_type,r.entity_id,r.rating_kind,r.score,r.comment,r.created_at
from public.customer_ratings r
join public.customer_interactions i on i.id=r.interaction_id
where i.verified=true;

