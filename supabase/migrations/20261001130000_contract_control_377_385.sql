-- Canonical contract control for checklist 377-385.
-- Extends the existing BuildWiseContract responsibility; no parallel contract engine.

create table if not exists public.contract_templates (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  body text not null default '',
  variables jsonb not null default '{}'::jsonb,
  status text not null default 'active' check (status in ('draft','active','archived')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contracts (
  id bigint generated by default as identity primary key,
  template_id bigint references public.contract_templates(id) on delete set null,
  deal_id bigint,
  project_id bigint,
  title text not null,
  subject text not null default '',
  consideration numeric not null default 0,
  status text not null default 'draft' check (status in ('draft','pending_approval','approved','pending_signature','signed','active','breached','closed','cancelled')),
  current_version integer not null default 1,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contract_versions (
  id bigint generated by default as identity primary key,
  contract_id bigint not null references public.contracts(id) on delete cascade,
  version integer not null,
  snapshot jsonb not null default '{}'::jsonb,
  change_note text not null default '',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique(contract_id, version)
);

create table if not exists public.contract_attachments (
  id bigint generated by default as identity primary key,
  contract_id bigint not null references public.contracts(id) on delete cascade,
  file_id bigint,
  title text not null default '',
  status text not null default 'active' check (status in ('active','superseded','removed')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.contract_approvals (
  id bigint generated by default as identity primary key,
  contract_id bigint not null references public.contracts(id) on delete cascade,
  approver_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  comment text not null default '',
  decided_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.contract_signatures (
  id bigint generated by default as identity primary key,
  contract_id bigint not null references public.contracts(id) on delete cascade,
  signer_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','signed','declined','void')),
  signature_ref text,
  signed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.contract_obligations (
  id bigint generated by default as identity primary key,
  contract_id bigint not null references public.contracts(id) on delete cascade,
  title text not null,
  amount numeric not null default 0,
  due_at timestamptz,
  status text not null default 'open' check (status in ('open','fulfilled','overdue','cancelled')),
  fulfilled_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.contract_milestones (
  id bigint generated by default as identity primary key,
  contract_id bigint not null references public.contracts(id) on delete cascade,
  title text not null,
  due_at timestamptz,
  status text not null default 'pending' check (status in ('pending','completed','overdue','cancelled')),
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.contract_breach_alerts (
  id bigint generated by default as identity primary key,
  contract_id bigint not null references public.contracts(id) on delete cascade,
  title text not null,
  severity text not null default 'medium' check (severity in ('low','medium','high','critical')),
  status text not null default 'open' check (status in ('open','acknowledged','resolved')),
  detected_at timestamptz not null default now(),
  resolved_at timestamptz
);

