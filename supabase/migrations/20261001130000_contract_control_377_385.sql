create or replace view public.contract_control as
select
  c.id,
  c.deal_id,
  c.project_id,
  c.title,
  c.status,
  c.current_version,
  count(distinct v.id) as version_count,
  count(distinct a.id) as attachment_count,
  count(distinct ap.id) filter (where ap.status='pending') as pending_approvals,
  count(distinct s.id) filter (where s.status='pending') as pending_signatures,
  count(distinct o.id) filter (where o.status in ('open','overdue')) as open_obligations,
  count(distinct m.id) filter (where m.status in ('pending','overdue')) as open_milestones,
  count(distinct b.id) filter (where b.status in ('open','acknowledged')) as open_breaches
from public.contracts c
left join public.contract_versions v on v.contract_id=c.id
left join public.contract_attachments a on a.contract_id=c.id
left join public.contract_approvals ap on ap.contract_id=c.id
left join public.contract_signatures s on s.contract_id=c.id
left join public.contract_obligations o on o.contract_id=c.id
left join public.contract_milestones m on m.contract_id=c.id
left join public.contract_breach_alerts b on b.contract_id=c.id
group by c.id,c.deal_id,c.project_id,c.title,c.status,c.current_version;
